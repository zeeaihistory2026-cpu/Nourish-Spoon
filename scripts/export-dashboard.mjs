import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// The separate Vercel repository is generated from this app's canonical sources.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.resolve(root, process.argv[2] || "tmp/dashboard-release");
if (
  !["tmp", "artifacts"].some((folder) =>
    target.startsWith(path.join(root, folder) + path.sep),
  )
)
  throw Error("Export must use a dedicated folder inside tmp/ or artifacts/.");
await fs.mkdir(target, { recursive: true });
// Replace generated trees completely so deleted routes and assets cannot survive a release.
// Git metadata and environment files in a deployment checkout are preserved.
for (const name of ["src", "public", "docs", "tsconfig.tsbuildinfo", "netlify.toml"])
  await fs.rm(path.join(target, name), { recursive: true, force: true });
await fs.writeFile(path.join(target, ".gitignore"), "node_modules/\n.next/\nout/\nbuild/\n.vercel/\n*.tsbuildinfo\n*.log\n*.apk\n*.aab\n*.apks\n*.ipa\n.env*\n!.env.example\n*.pem\n*.jks\n*.keystore\n.DS_Store\n");
await fs.writeFile(path.join(target, ".gitattributes"), "* text=auto eol=lf\n");
await fs.copyFile(path.join(root, ".editorconfig"), path.join(target, ".editorconfig"));
for (const name of [
  "src",
  "public",
  "docs",
  "README.md",
  "package.json",
  "package-lock.json",
  "tsconfig.json",
  "next.config.ts",
  "vercel.json",
  "next-env.d.ts",
  ".env.example",
  "AGENTS.md",
])
  await fs.cp(path.join(root, "apps/admin", name), path.join(target, name), {
    recursive: true,
    force: true,
  });
const shared = path.join(target, "src/server-shared");
await fs.mkdir(path.join(shared, "commerce"), { recursive: true });
await fs.mkdir(path.join(shared, "catalog"), { recursive: true });
for (const name of [
  "adminOrders.js",
  "customerOrders.js",
  "customerReviews.js",
  "customerPhotos.js",
  "domain.js",
  "rewards.js",
  "rewardRules.js",
])
  await fs.copyFile(
    path.join(root, "functions/src", name),
    path.join(shared, "commerce", name),
  );
await fs.copyFile(
  path.join(root, "packages/catalog/normalizeProduct.js"),
  path.join(shared, "catalog/normalizeProduct.js"),
);
await fs.copyFile(
  path.join(root, "packages/catalog/normalizeProduct.d.ts"),
  path.join(shared, "catalog/normalizeProduct.d.ts"),
);
await fs.cp(path.join(root, "packages/types"), path.join(shared, "types"), {
  recursive: true,
  force: true,
});
await fs.mkdir(path.join(shared, "lib"), { recursive: true });
await fs.copyFile(
  path.join(root, "functions/lib/normalizeProduct.js"),
  path.join(shared, "lib/normalizeProduct.js"),
);
await fs.copyFile(
  path.join(root, "functions/lib/delivery.js"),
  path.join(shared, "lib/delivery.js"),
);
await fs.writeFile(
  path.join(shared, "package.json"),
  JSON.stringify({ type: "commonjs" }) + "\n",
);
await fs.writeFile(
  path.join(shared, "catalog/package.json"),
  JSON.stringify({ type: "module" }) + "\n",
);
for (const name of await fs.readdir(path.join(target, "src/lib"))) {
  if (!name.endsWith(".ts")) continue;
  const file = path.join(target, "src/lib", name);
  const text = (await fs.readFile(file, "utf8"))
    .replaceAll("../../../../functions/src/", "../server-shared/commerce/")
    .replaceAll("../../../../packages/catalog/", "../server-shared/catalog/");
  await fs.writeFile(file, text);
}
await fs.writeFile(
  path.join(shared, "README.md"),
  "Generated by scripts/export-dashboard.mjs from Nourish-Spoon. Edit the canonical monorepo, then export again. Never store server credentials in source.\n",
);
console.log(
  "Exported dashboard with shared order, stock, reward and promo transactions: " +
    path.relative(root, target),
);
